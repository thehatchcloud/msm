// Package install generates the files a manual installation needs: the
// manager configuration, data directories, a systemd unit or a launchd
// property list, and the prerequisite report. It writes only what it is
// asked to, never installs a package, and never enables or starts a service
// unless explicitly told to.
package install

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"strings"

	"github.com/thehatchcloud/msm/internal/atomicfile"
	"github.com/thehatchcloud/msm/internal/identity"
)

// ErrExists: a file already exists with different content.
var ErrExists = errors.New("install: file already exists")

// ErrUnsafe: a value cannot be written into a generated file safely.
var ErrUnsafe = errors.New("install: unsafe value")

// safePath admits the characters of ordinary install locations and nothing
// that a shell, systemd, a property list or msm.conf would interpret.
var safePath = regexp.MustCompile(`^/[A-Za-z0-9._/+@:-]*$`)

var userName = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9._-]{0,31}$`)

func checkPath(what, p string) error {
	if !safePath.MatchString(p) || strings.Contains(p, "/../") || strings.HasSuffix(p, "/..") {
		return fmt.Errorf("%w: %s %q must be an absolute path of letters, digits and . _ / + @ : - only", ErrUnsafe, what, p)
	}
	return nil
}

func checkUser(u string) error {
	if !userName.MatchString(u) {
		return fmt.Errorf("%w: user name %q", ErrUnsafe, u)
	}
	return nil
}

// Check is one prerequisite and, when it is missing, how to get it.
type Check struct {
	Name     string
	Required string // what needs it
	Path     string // where it was found; empty when missing
	Hint     string
}

// Prerequisites reports GNU screen and Java. lookPath is exec.LookPath in
// production. Nothing is installed; a missing program only gets a hint.
func Prerequisites(goos string, lookPath func(string) (string, error)) []Check {
	screenHint := "Debian/Ubuntu: sudo apt install screen; Fedora/RHEL: sudo dnf install screen; Arch: sudo pacman -S screen"
	javaHint := "Debian/Ubuntu: sudo apt install default-jre-headless; Fedora/RHEL: sudo dnf install java-latest-openjdk-headless; Arch: sudo pacman -S jre-openjdk-headless; any system: https://adoptium.net/"
	if goos == "darwin" {
		screenHint = "brew install screen (the screen macOS bundles, 4.00.03, is too old and is refused)"
		javaHint = "brew install openjdk, then follow the symlink instruction brew prints; or https://adoptium.net/"
	}
	checks := []Check{
		{Name: "screen", Required: "running servers (start, stop, console)", Hint: screenHint},
		{Name: "java", Required: "running Minecraft servers", Hint: javaHint},
	}
	for i := range checks {
		if p, err := lookPath(checks[i].Name); err == nil {
			checks[i].Path = p
		}
	}
	return checks
}

// ConfigOptions describes a generated msm.conf.
type ConfigOptions struct {
	Path     string
	Username string
	Servers  string
	Jars     string
	Archives string // directory holding worlds/, backups/ and logs/
	Force    bool
	// Lookup resolves Username; identity.Lookup in production.
	Lookup func(string) (identity.Identity, error)
}

// ConfigText renders msm.conf.
func ConfigText(o ConfigOptions) (string, error) {
	if err := checkUser(o.Username); err != nil {
		return "", err
	}
	for what, p := range map[string]string{"server directory": o.Servers, "JAR directory": o.Jars, "archive directory": o.Archives} {
		if err := checkPath(what, p); err != nil {
			return "", err
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Minecraft Server Manager configuration, generated by \"msm install config\".\n")
	fmt.Fprintf(&b, "# Every other setting keeps its default; see \"msm config\" for the full list.\n\n")
	fmt.Fprintf(&b, "USERNAME=%q\n", o.Username)
	fmt.Fprintf(&b, "DEFAULT_USERNAME=%q\n\n", o.Username)
	fmt.Fprintf(&b, "SERVER_STORAGE_PATH=%q\n", o.Servers)
	fmt.Fprintf(&b, "JAR_STORAGE_PATH=%q\n", o.Jars)
	fmt.Fprintf(&b, "WORLD_ARCHIVE_PATH=%q\n", o.Archives+"/worlds")
	fmt.Fprintf(&b, "BACKUP_ARCHIVE_PATH=%q\n", o.Archives+"/backups")
	fmt.Fprintf(&b, "LOG_ARCHIVE_PATH=%q\n", o.Archives+"/logs")
	return b.String(), nil
}

// WriteConfig creates the configuration file and the data directories it
// names, owned by the manager user when running as root. It refuses to
// replace a different existing file unless Force is set, and never touches
// the contents of an existing data directory.
func WriteConfig(o ConfigOptions) (created []string, err error) {
	if err := checkPath("configuration file", o.Path); err != nil {
		return nil, err
	}
	text, err := ConfigText(o)
	if err != nil {
		return nil, err
	}
	owner, err := o.Lookup(o.Username)
	if err != nil {
		return nil, fmt.Errorf("install: manager user %q does not exist; create it first (for example: sudo useradd --system --create-home --shell /usr/sbin/nologin %s on Linux): %w", o.Username, o.Username, err)
	}
	if old, err := os.ReadFile(o.Path); err == nil {
		if string(old) == text {
			return nil, nil
		}
		if !o.Force {
			return nil, fmt.Errorf("%w: %s differs from what would be generated; review it, or pass --force to replace it", ErrExists, o.Path)
		}
	}
	for _, dir := range []string{o.Servers, o.Jars, o.Archives + "/worlds", o.Archives + "/backups", o.Archives + "/logs"} {
		made, err := mkdirAll(dir, owner)
		if err != nil {
			return created, err
		}
		created = append(created, made...)
	}
	if err := atomicfile.Write(o.Path, []byte(text), 0o644); err != nil {
		return created, err
	}
	return append(created, o.Path), nil
}

// mkdirAll creates dir and any missing parents, giving the directories it
// created (and only those) to owner when running as root.
func mkdirAll(dir string, owner identity.Identity) ([]string, error) {
	var missing []string
	for d := dir; d != "/" && d != "."; d = parent(d) {
		if _, err := os.Stat(d); err == nil {
			break
		}
		missing = append([]string{d}, missing...)
	}
	for _, d := range missing {
		if err := os.Mkdir(d, 0o755); err != nil {
			return nil, fmt.Errorf("install: create %s: %w", d, err)
		}
		if os.Geteuid() == 0 {
			if err := os.Chown(d, owner.UID, owner.GID); err != nil {
				return nil, fmt.Errorf("install: give %s to %s: %w", d, owner.Username, err)
			}
		}
	}
	return missing, nil
}

func parent(p string) string {
	i := strings.LastIndex(p, "/")
	if i <= 0 {
		return "/"
	}
	return p[:i]
}

// Runner runs an external program with an explicit argument list (no shell).
type Runner func(name string, args ...string) error

// ExecRunner is the production Runner.
func ExecRunner(name string, args ...string) error {
	out, err := exec.Command(name, args...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("install: %s %s: %w: %s", name, strings.Join(args, " "), err, strings.TrimSpace(string(out)))
	}
	return nil
}
